#!/usr/bin/env node
// fm-branch-dispatch-build.mjs - regenerate, or check, the plain-JavaScript
// copy of the supervision-branch dispatch library that bin/fm-branch-dispatch.mjs
// loads on a Node.js without TypeScript support.
//
// .pi/extensions/lib/fm-branch-dispatch.ts stays the single owner of the
// dispatch rules. Some Node.js builds cannot load it at all: distribution
// packages such as Ubuntu's Node 22 are compiled without the TypeScript
// stripper (process.features.typescript is false and --experimental-strip-types
// fails with ERR_NO_TYPESCRIPT), and Node before 22.18 needs a flag. On those,
// the dispatch entry imports the generated copy under bin/fm-branch-dispatch-js/
// instead, so a supervision host there still classifies wakes rather than
// handing every one to main.
//
// The copy is produced by Node's own type stripper (module.stripTypeScriptTypes),
// which only erases type syntax, with each relative "./<name>.ts" import
// rewritten to "./<name>.mjs" and trailing whitespace trimmed. Every relative
// .ts import a listed source makes must itself be a listed source, so the copy
// is complete. Never edit the generated files by hand; edit the .ts owner and
// rerun this script.
//
// Usage:
//   fm-branch-dispatch-build.mjs           rewrite the generated copy
//   fm-branch-dispatch-build.mjs --check   exit 1, naming each file, when the
//                                          generated copy is missing or stale
// Exit 0 on success, 1 on a stale copy under --check or an incomplete source
// list, 2 on invalid use or when this Node.js has no TypeScript stripper.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import module from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.join(root, ".pi", "extensions", "lib");
const outDir = path.join(root, "bin", "fm-branch-dispatch-js");
const sources = ["fm-branch-dispatch", "fm-async-exec"];

const args = process.argv.slice(2);
const check = args.length === 1 && args[0] === "--check";
if (args.length > (check ? 1 : 0)) {
  process.stderr.write("usage: fm-branch-dispatch-build.mjs [--check]\n");
  process.exit(2);
}

function strip(code) {
  if (typeof module.stripTypeScriptTypes !== "function") {
    throw Object.assign(new Error("module.stripTypeScriptTypes is unavailable"), { code: "ERR_NO_TYPESCRIPT" });
  }
  const emit = process.emitWarning;
  process.emitWarning = () => {};
  try {
    return module.stripTypeScriptTypes(code, { mode: "strip" });
  } finally {
    process.emitWarning = emit;
  }
}

function generate(name) {
  const source = readFileSync(path.join(sourceDir, `${name}.ts`), "utf8");
  let stripped;
  try {
    stripped = strip(source);
  } catch (error) {
    if (error?.code === "ERR_NO_TYPESCRIPT") {
      process.stderr.write("fm-branch-dispatch-build.mjs: this Node.js has no TypeScript stripper; run it with a Node.js that does\n");
      process.exit(2);
    }
    throw error;
  }
  const body = stripped.replace(/(\bfrom\s+|\bimport\s*\(\s*)(["'])\.\/([^"'/]+)\.ts\2/g, (match, lead, quote, target) => {
    if (!sources.includes(target)) {
      process.stderr.write(`fm-branch-dispatch-build.mjs: ${name}.ts imports ./${target}.ts, which is not a listed source\n`);
      process.exit(1);
    }
    return `${lead}${quote}./${target}.mjs${quote}`;
  });
  const header =
    `// GENERATED by bin/fm-branch-dispatch-build.mjs from .pi/extensions/lib/${name}.ts - do not edit.\n` +
    "// Edit the .ts owner and rerun that script.\n";
  return header + body.replace(/[ \t]+$/gm, "").replace(/\n+$/, "\n");
}

let stale = 0;
if (!check) mkdirSync(outDir, { recursive: true });
for (const name of sources) {
  const target = path.join(outDir, `${name}.mjs`);
  const want = generate(name);
  if (check) {
    let have = null;
    try {
      have = readFileSync(target, "utf8");
    } catch {}
    if (have !== want) {
      process.stderr.write(`fm-branch-dispatch-build.mjs: ${path.relative(root, target)} is stale; rerun bin/fm-branch-dispatch-build.mjs\n`);
      stale = 1;
    }
  } else {
    writeFileSync(target, want);
  }
}
process.exit(stale);
